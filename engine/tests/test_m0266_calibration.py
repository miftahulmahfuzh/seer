"""M0266's calibration is arithmetic, and arithmetic can be pinned.

The whole worth of M0266 rests on one claim: the target-weight scale on each arm was derived from
exposures recorded BEFORE the method existed, by a formula with no return in it, and was written
into the method file before the run. A reader cannot verify that from the prose alone -- they have
to be able to recompute it. So these tests recompute it:

- the two scales really are ``exposure(M0127-E1) / exposure(M0127's arm at that band)``, rounded
  to the engine's millionth, and not numbers chosen to make an answer come out;
- scaling is the identity at 1, so the two control arms are M0127's allocator byte for byte and
  their trials must reproduce rows 875 and 879;
- the scaled arms hold exactly ``floor(scale / 50)`` per name, which is what makes the predicted
  average exposures in the file's docstring checkable;
- the six arms differ in nothing but their rule set and their scale.

These numbers are frozen. If one of them has to move, the method has been re-fitted and the
measurement is void: register a new method, do not edit this file.
"""

from __future__ import annotations

from decimal import ROUND_HALF_UP, Decimal

import pytest
from labkit import MEMBER_STOCKS, SMOKE_FIRST, smoke_market

from seer_engine import dates
from seer_engine.backtest.dev import DEV_END

from seer_engine.lab.methods import m0127_slot_relative_resize_band as m127
from seer_engine.lab.methods import m0266_exposure_matched_rebalance as m266

MILLIONTH = Decimal("0.000001")
ARMS = {c.id: c for c in m266.METHOD.candidates}


def test_the_scales_are_the_preregistered_ratio_and_nothing_else():
    """Each scale is recorded-exposure over recorded-exposure, to a millionth. No return in it."""
    assert m266.SCALE_T00 == (m266.EXPOSURE_E1 / m266.EXPOSURE_T00).quantize(
        MILLIONTH, rounding=ROUND_HALF_UP
    )
    assert m266.SCALE_T20 == (m266.EXPOSURE_E1 / m266.EXPOSURE_T20).quantize(
        MILLIONTH, rounding=ROUND_HALF_UP
    )
    # The ruler deliberately reuses the treatment's step rather than inventing a third one, so
    # that L -> LS and T00 -> T00M are the identical downward move on two different bands.
    assert m266.SCALE_RULER == m266.SCALE_T00


def test_the_predicted_exposures_in_the_docstring_are_what_the_arithmetic_gives():
    """Floored weights, times fifty, times the recorded exposure: the file's 0.886430/0.886456."""
    w00 = (Decimal("0.02") * m266.SCALE_T00).quantize(MILLIONTH, rounding="ROUND_DOWN")
    w20 = (Decimal("0.02") * m266.SCALE_T20).quantize(MILLIONTH, rounding="ROUND_DOWN")
    assert (w00, w20) == (Decimal("0.017986"), Decimal("0.018428"))
    assert (50 * w00, 50 * w20) == (Decimal("0.899300"), Decimal("0.921400"))
    for predicted, exposure, weight in (
        (Decimal("0.886430"), m266.EXPOSURE_T00, w00),
        (Decimal("0.886456"), m266.EXPOSURE_T20, w20),
    ):
        assert (50 * weight * exposure).quantize(MILLIONTH, rounding=ROUND_HALF_UP) == predicted
        # ... and every one of them is within half a point of the control's own exposure, which
        # is the precondition the method's analysis has to verify on the REALISED figures.
        assert abs(50 * weight * exposure - m266.EXPOSURE_E1) < Decimal("0.005")


SESSIONS = dates.sessions(SMOKE_FIRST, DEV_END)


@pytest.mark.parametrize("day", [SESSIONS[60], SESSIONS[250], SESSIONS[-1]])
def test_scale_one_is_m0127s_allocator_byte_for_byte(day):
    """The control arms must reproduce M0127's recorded trials, so they must pick identically."""
    market = smoke_market()
    members = frozenset(MEMBER_STOCKS)
    hist = market.history
    d = day
    ours = m266.BOOK.targets(hist, members, d, frozenset(), m266.ScaledBandParams())
    theirs = m127.BOOK.targets(hist, members, d, frozenset(), m127.BandParams())
    assert ours == theirs
    assert ours, "the smoke book must hold something, or this test proves nothing"


@pytest.mark.parametrize("scale", [m266.SCALE_T00, m266.SCALE_T20])
def test_a_scaled_arm_holds_the_same_names_at_the_floored_fraction(scale):
    """Same symbols, same order, every weight floored to ``scale`` times the unscaled weight."""
    market = smoke_market()
    members = frozenset(MEMBER_STOCKS)
    d = SESSIONS[250]
    full = m266.BOOK.targets(market.history, members, d, frozenset(), m266.ScaledBandParams())
    cut = m266.BOOK.targets(
        market.history, members, d, frozenset(), m266.ScaledBandParams(scale=scale)
    )
    assert [t.symbol for t in cut] == [t.symbol for t in full]
    for a, b in zip(full, cut, strict=True):
        assert b.weight == (a.weight * scale).quantize(MILLIONTH, rounding="ROUND_DOWN")
        assert b.last == a.last


def test_the_six_arms_differ_only_in_their_band_and_their_scale():
    """One allocator, one screen, six arms: anything else differing would confound the split."""
    assert set(ARMS) == {"M0266-L", "M0266-T00", "M0266-T00M", "M0266-T20", "M0266-T20M",
                         "M0266-LS"}
    for c in ARMS.values():
        assert c.allocator is m266.BOOK
        assert (c.params.top, c.params.min_dollar_volume, c.params.min_price) == (
            50, 20_000_000.0, 5.0
        )
        assert c.rules.cost_model == "gotrade" and c.rules.fractional
    # The matched pairs: same band as their unscaled twin, the calibrated scale.
    assert ARMS["M0266-T00M"].rules is ARMS["M0266-T00"].rules
    assert ARMS["M0266-T20M"].rules is ARMS["M0266-T20"].rules
    assert ARMS["M0266-LS"].rules is ARMS["M0266-L"].rules
    assert ARMS["M0266-T00M"].params.scale == m266.SCALE_T00
    assert ARMS["M0266-T20M"].params.scale == m266.SCALE_T20
    assert ARMS["M0266-LS"].params.scale == m266.SCALE_RULER
    for cid in ("M0266-L", "M0266-T00", "M0266-T20"):
        assert ARMS[cid].params.scale == Decimal(1)
    # And the bands themselves are M0127's own objects, so the two methods cannot drift apart.
    assert (m266.LOOSE, m266.TIGHT20, m266.TIGHT00) == (m127.E1, m127.T20, m127.T00)
