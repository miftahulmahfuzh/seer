"""M0270's ladder is six round numbers and one dial, and both claims can be pinned.

The worth of M0270 rests on claims a reader cannot check from the prose alone:

- the rungs are ROUND NUMBERS, evenly spaced, and not derived from any recorded exposure -- that
  is the whole reason the x axis is a measurement rather than a calibration, and the reason this
  ladder cannot suffer the transfer failure that stopped M0266 publishing a split on the check
  store;
- the band is constant across every arm, so ``scale`` is the only thing that moves;
- the allocator is M0266's, inherited rather than re-implemented, so the top rung must reproduce
  M0266-T00 to the digit -- and the proof of that is that not one targets method is overridden;
- the new allocator id is what separates the ladder's digests from M0266's recorded trials, so
  every arm's digest must be distinct from every arm of M0266's.

These numbers are frozen. If one of them has to move, the method has been re-fitted and the
measurement is void: register a new method, do not edit this file.
"""

from __future__ import annotations

from decimal import Decimal

from seer_engine.lab.method import config_digest
from seer_engine.lab.methods import m0127_slot_relative_resize_band as m127
from seer_engine.lab.methods import m0266_exposure_matched_rebalance as m266
from seer_engine.lab.methods import m0270_exposure_return_curve as m270

ARMS = tuple(m270.METHOD.candidates)
STEP = Decimal("0.06")


def test_the_rungs_are_round_numbers_evenly_spaced_from_seventy_to_one_hundred():
    """Round numbers, 0.06 apart, 0.70 to 1.00. No recorded exposure appears anywhere in them."""
    assert m270.SCALES == (
        Decimal("1.00"), Decimal("0.94"), Decimal("0.88"),
        Decimal("0.82"), Decimal("0.76"), Decimal("0.70"),
    )
    gaps = [a - b for a, b in zip(m270.SCALES, m270.SCALES[1:])]
    assert gaps == [STEP] * 5, "uneven rungs would let spacing masquerade as curvature"
    assert m270.SCALES[0] == 1 and m270.SCALES[-1] == Decimal("0.70")


def test_the_scales_are_not_a_calibration():
    """No rung is the recorded exposure, or a ratio of recorded exposures, to a millionth.

    This is the structural difference from M0266, whose scales WERE such a ratio and whose
    calibration is exactly what failed to transfer to the second store.
    """
    recorded = (m266.EXPOSURE_E1, m266.EXPOSURE_T20, m266.EXPOSURE_T00)
    derived = {r.quantize(Decimal("0.000001")) for r in recorded}
    derived |= {(a / b).quantize(Decimal("0.000001")) for a in recorded for b in recorded if a != b}
    derived |= {m266.SCALE_T00, m266.SCALE_T20}
    for s in m270.SCALES:
        assert s.quantize(Decimal("0.000001")) not in derived


def test_every_arm_runs_the_same_band_and_it_is_m0127s():
    """The band is held still so that ``scale`` is the only moving part. Imported, not re-typed."""
    assert m270.BAND is m127.T00
    assert m270.BAND.resize_band == Decimal("0")
    assert {c.rules for c in ARMS} == {m127.T00}
    assert all(c.rules.fractional for c in ARMS)
    assert all(c.rules.cost_model == "gotrade" for c in ARMS)


def test_the_arms_differ_in_the_scale_and_in_nothing_else():
    assert len(ARMS) == 6
    assert tuple(c.params.scale for c in ARMS) == m270.SCALES
    assert tuple(c.id for c in ARMS) == (
        "M0270-S100", "M0270-S094", "M0270-S088", "M0270-S082", "M0270-S076", "M0270-S070",
    )
    assert {c.allocator for c in ARMS} == {m270.BOOK}
    assert {(c.params.top, c.params.min_dollar_volume, c.params.min_price) for c in ARMS} == {
        (50, 20_000_000.0, 5.0)
    }
    assert all(c.owner_inputs == () for c in ARMS)


def test_the_allocator_is_m0266s_inherited_and_not_one_line_of_it_reimplemented():
    """Prediction 2 -- the top rung reproduces M0266-T00 -- is only a real check if this holds."""
    assert isinstance(m270.BOOK, m266.ScaledMostTradedEqualWeight)
    assert m270.BOOK.id == "M0270" != m266.BOOK.id
    own = vars(m270.ExposureLadderBook)
    assert not [k for k, v in own.items() if callable(v)], "no method may be re-implemented"
    assert set(own) <= {"__doc__", "__module__", "__annotations__", "id"}
    assert type(ARMS[0].params) is type(m266.METHOD.candidates[0].params)


def test_the_top_rung_is_the_identity_on_weights():
    """``scale == 1`` must be a no-op, or the top rung is not M0266-T00's configuration."""
    assert m270.SCALES[0] == 1
    assert m266._scaled((), m270.SCALES[0]) == ()


def test_no_arm_collides_with_a_recorded_m0266_configuration():
    """The allocator id is the whole separation; if it ever stopped working the lab would refuse."""
    ours = {config_digest(c) for c in ARMS}
    theirs = {config_digest(c) for c in m266.METHOD.all_candidates()}
    assert len(ours) == 6
    assert ours.isdisjoint(theirs)


def test_the_predicted_exposures_are_monotone_and_span_thirty_points():
    """Prediction 1's x axis: strictly decreasing, and wide enough to be a function not a pair."""
    predicted = [s * m270.EXPOSURE_AT_FULL_WEIGHT for s in m270.SCALES]
    assert all(a > b for a, b in zip(predicted, predicted[1:]))
    assert Decimal("0.29") < predicted[0] - predicted[-1] < Decimal("0.31")


def test_the_method_row_is_what_the_lab_will_record():
    assert m270.METHOD.id == "M0270"
    assert m270.METHOD.family == "portfolio-rebalancing"
    assert m270.METHOD.parent_id == "M0266"
    assert m270.METHOD.source_kind == "variation"
